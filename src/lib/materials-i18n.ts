const DICTS: Record<Lang, MaterialsDict> = { ru, en, pl, ro, uk, nl };

export function getMaterialsDict(lang: Lang): MaterialsDict {
  return DICTS[lang];
}

// The message the worker sends to the client (Dutch).
export function materialsMessage(input: { clientName: string | null; title: string; url: string; worker: string }) {
  return [
    `Beste${input.clientName ? ` ${input.clientName}` : ""},`,
    "",
    `Hierbij de materiaallijst voor ${input.title}: ${input.url}`,
    "U ziet de producten met prijzen en kunt kiezen of ik de materialen regel of dat u ze zelf koopt.",
    "",
    "Met vriendelijke groet,",
    input.worker,
  ].join("\n");
}

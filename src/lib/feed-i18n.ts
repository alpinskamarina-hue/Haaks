export function getFeedDict(lang: Lang): FeedDict {
  return dicts[lang];
}

export function fill(text: string, values: Record<string, string | number>) {
  return text.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}


const DICTS: Record<Lang, WorkerDict> = { en, pl, ro, uk, ru, tr, nl };

export function getWorkerDict(lang: Lang): WorkerDict {
  return DICTS[lang];
}

export function yearsText(w: WorkerDict, lang: Lang, n: number) {
  const form = new Intl.PluralRules(lang).select(n) as keyof WorkerDict["years"];
  return (w.years[form] ?? w.years.other).replace("{n}", String(n));
}

export function radiusText(w: WorkerDict, km: number) {
  return km === 0 ? w.wholeCountry : w.km.replace("{n}", String(km));
}


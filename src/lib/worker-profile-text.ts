type Lists = Pick<
  WorkerProfile,
  | "trades" | "trade_levels" | "city" | "travel_km" | "extra_cities" | "languages" | "language_levels"
  | "vehicle" | "licences" | "tools" | "equipment" | "works_with" | "team_size"
>;

// The profile as short lines of text, in the given language. Empty strings mean "not filled in".
export function describeProfile(p: Lists, w: WorkerDict, lang: Lang) {
  const label = <K extends keyof WorkerDict>(group: K, id: string | null) =>
    id ? ((w[group] as Record<string, string>)[id] ?? "") : "";
  const trades = p.trades.map((id) => {
    const lv = p.trade_levels?.[id] ?? {};
    const parts = [label("levels", lv.level ?? null), lv.years ? yearsText(w, lang, lv.years) : ""].filter(Boolean);
    return { name: label("trades", id), detail: parts.join(" · ") };
  });
  const region = p.city
    ? [p.travel_km === 0 ? w.wholeCountry : p.travel_km !== null ? `${p.city} + ${radiusText(w, p.travel_km)}` : p.city, ...p.extra_cities].join(", ")
    : p.extra_cities.join(", ");
  const languages = p.languages.map((id) => ({
    name: label("spoken", id),
    level: label("langLevels", p.language_levels?.[id] ?? "basic"),
  }));
  const transport = p.vehicle
    ? [label("vehicle", p.vehicle), p.vehicle !== "none" && p.licences.length ? p.licences.join(", ") : ""].filter(Boolean).join(" · ")
    : "";
  const tools = p.tools ? [label("tools", p.tools), ...p.equipment.map((e) => label("equipment", e))].filter(Boolean).join(", ") : "";
  const team = p.works_with
    ? p.works_with === "team" && p.team_size
      ? w.teamOf.replace("{n}", String(p.team_size))
      : label("worksWith", p.works_with)
    : "";
  return { trades, region, languages, transport, tools, team };
}

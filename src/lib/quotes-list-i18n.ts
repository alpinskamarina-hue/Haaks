// A job ad's headline ("Loodgieter gezocht: verstopte gootsteen, Nieuwegein") as a name
// for the work ("Verstopte gootsteen, Nieuwegein"). Null when it does not look like an ad.
export function workTitleFromAd(title: string): string | null {
  const patterns = [
    /^\s*[\p{L}\s/-]{0,40}?\b(gezocht|gevraagd|nodig)\b\s*(voor|om|bij)?\s*[:\-–—!]?\s*/iu,
    /^\s*(wie|hulp)\s+(kan|gezocht|nodig)\b[^:]*[:\-–—]\s*/iu,
  ];
  for (const re of patterns) {
    const rest = title.replace(re, "").trim();
    if (rest !== title.trim() && rest.length >= 4) return rest.charAt(0).toUpperCase() + rest.slice(1);
  }
  return null;
}


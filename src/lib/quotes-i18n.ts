export const getQuotesDict = (lang: Lang) => DICTS[lang];

export const fill = (text: string, values: Record<string, string | number>) =>
  text.replace(/\{(\w+)\}/g, (_, k) => String(values[k] ?? ""));

// "today", "yesterday", "3 days ago" in the worker's language.
export function whenText(iso: string, lang: Lang) {
  const day = (d: Date) => Math.floor(d.getTime() / 86400000);
  const diff = day(new Date(iso)) - day(new Date());
  return new Intl.RelativeTimeFormat(lang, { numeric: "auto" }).format(diff, "day");
}

export const daysSince = (iso: string) => Math.floor((Date.now() - new Date(iso).getTime()) / 86400000);

// Polite Dutch reminder for a client who has not answered yet.
export function reminderMessage(input: { clientName: string | null; title: string; link: string; worker: string | null }) {
  const hello = input.clientName ? `Beste ${input.clientName},` : "Goedendag,";
  return [
    hello,
    "",
    `Een paar dagen geleden heb ik u de offerte voor "${input.title}" gestuurd. Heeft u de tijd gehad om ernaar te kijken?`,
    "Als u vragen heeft of iets anders wilt, pas ik de offerte graag aan.",
    "",
    `De offerte: ${input.link}`,
    "",
    "Met vriendelijke groet,",
    input.worker ?? "",
  ].join("\n");
}
